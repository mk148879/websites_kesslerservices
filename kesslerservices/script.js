function currentPage() {
  return window.location.pathname.split("/").pop() || "index.html";
}

function storedLanguage() {
  try {
    return window.localStorage.getItem("ks-language");
  } catch {
    return null;
  }
}

function rememberLanguage(language) {
  try {
    window.localStorage.setItem("ks-language", language);
  } catch {
    // The language still changes for the current page if storage is unavailable.
  }
}

const topbar = document.querySelector(".topbar");
const menuToggle = document.querySelector("[data-menu-toggle]");
const navLinks = document.querySelectorAll(".nav-links a");

function applyLanguage(language) {
  const nextLanguage = translations[language] ? language : "en";
  const dictionary = translations[nextLanguage];

  document.documentElement.lang = nextLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    const isActive = button.dataset.langOption === nextLanguage;
    button.setAttribute("aria-pressed", String(isActive));
  });

  updateMenuLabel(dictionary);

  const title = pageTitles[nextLanguage][currentPage()];
  if (title) document.title = title;

  rememberLanguage(nextLanguage);
}

document.querySelectorAll("[data-lang-option]").forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.langOption);
  });
});

applyLanguage(storedLanguage() || "en");

function activeDictionary() {
  return translations[document.documentElement.lang] || translations.en;
}

function updateMenuLabel(dictionary = activeDictionary()) {
  if (!menuToggle) return;
  const isOpen = topbar.classList.contains("is-menu-open");
  menuToggle.setAttribute("aria-label", isOpen ? dictionary["nav.menu.close"] : dictionary["nav.menu.open"]);
}

function setMenuOpen(isOpen) {
  if (!topbar || !menuToggle) return;
  topbar.classList.toggle("is-menu-open", isOpen);
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  updateMenuLabel();
}

if (menuToggle) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    setMenuOpen(!isOpen);
  });
}

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    setMenuOpen(false);
  });
});

const canvas = document.querySelector("#signalCanvas");
const ctx = canvas.getContext("2d");
const steps = document.querySelectorAll(".step");
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

let width = 0;
let height = 0;
let particles = [];

function resizeCanvas() {
  const ratio = window.devicePixelRatio || 1;
  width = canvas.offsetWidth;
  height = canvas.offsetHeight;
  canvas.width = width * ratio;
  canvas.height = height * ratio;
  ctx.setTransform(ratio, 0, 0, ratio, 0, 0);

  particles = Array.from({ length: Math.min(84, Math.floor(width / 14)) }, () => ({
    x: Math.random() * width,
    y: Math.random() * height,
    vx: (Math.random() - 0.5) * 0.42,
    vy: (Math.random() - 0.5) * 0.42,
    r: Math.random() * 1.8 + 0.6
  }));
}

function drawNetwork() {
  ctx.clearRect(0, 0, width, height);
  ctx.fillStyle = "rgba(214, 170, 85, 0.58)";
  ctx.strokeStyle = "rgba(214, 170, 85, 0.12)";
  ctx.lineWidth = 1;

  particles.forEach((point) => {
    ctx.beginPath();
    ctx.arc(point.x, point.y, point.r, 0, Math.PI * 2);
    ctx.fill();
  });

  for (let i = 0; i < particles.length; i += 1) {
    for (let j = i + 1; j < particles.length; j += 1) {
      const a = particles[i];
      const b = particles[j];
      const distance = Math.hypot(a.x - b.x, a.y - b.y);

      if (distance < 138) {
        ctx.globalAlpha = 1 - distance / 138;
        ctx.beginPath();
        ctx.moveTo(a.x, a.y);
        ctx.lineTo(b.x, b.y);
        ctx.stroke();
      }
    }
  }

  ctx.globalAlpha = 1;
}

steps.forEach((step) => {
  step.addEventListener("click", () => {
    steps.forEach((item) => {
      item.classList.remove("is-active");
      item.setAttribute("aria-pressed", "false");
    });
    step.classList.add("is-active");
    step.setAttribute("aria-pressed", "true");
  });
});

function handleCanvasResize() {
  resizeCanvas();
  if (!reduceMotion) {
    drawNetwork();
  }
}

window.addEventListener("resize", handleCanvasResize);
handleCanvasResize();
